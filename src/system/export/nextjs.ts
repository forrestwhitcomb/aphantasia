// ── Main export function ────────────────────────────────────

export function generateNextJSProject(
  project: Project,
  tokens: Record<string, string>,
  darkTokens: Record<string, string>,
): ExportedProject {
  const files: Record<string, string> = {};
  const projectName = screenSlug(project.screens[0]?.name ?? "project");

  // Collect all used component types across all screens
  const allUsed = new Set<ComponentType>();
  for (const screen of project.screens) {
    for (const t of getUsedComponentTypes(screen.root)) allUsed.add(t);
  }

  // package.json
  const dependencies: Record<string, string> = {
    next: "^15.0.0",
    react: "^19.0.0",
    "react-dom": "^19.0.0",
    tailwindcss: "^4.0.0",
    "@tailwindcss/postcss": "^4.0.0",
  };
  const devDependencies: Record<string, string> = {
    typescript: "^5.0.0",
    "@types/react": "^19.0.0",
    "@types/node": "^22.0.0",
  };

  files["package.json"] = JSON.stringify({
    name: projectName,
    version: "0.1.0",
    private: true,
    scripts: { dev: "next dev", build: "next build", start: "next start" },
    dependencies,
    devDependencies,
  }, null, 2);

  // tsconfig.json
  files["tsconfig.json"] = JSON.stringify({
    compilerOptions: {
      target: "ES2017",
      lib: ["dom", "dom.iterable", "esnext"],
      allowJs: true,
      skipLibCheck: true,
      strict: true,
      noEmit: true,
      esModuleInterop: true,
      module: "esnext",
      moduleResolution: "bundler",
      resolveJsonModule: true,
      isolatedModules: true,
      jsx: "preserve",
      incremental: true,
      plugins: [{ name: "next" }],
      paths: { "@/*": ["./src/*"] },
    },
    include: ["next-env.d.ts", "**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
    exclude: ["node_modules"],
  }, null, 2);

  // next.config.ts
  files["next.config.ts"] = `import type { NextConfig } from "next";

const nextConfig: NextConfig = {};

export default nextConfig;
`;

  // postcss.config.mjs
  files["postcss.config.mjs"] = `/** @type {import('postcss-load-config').Config} */
const config = {
  plugins: {
    "@tailwindcss/postcss": {},
  },
};

export default config;
`;

  // globals.css
  files["src/app/globals.css"] = generateGlobalsCss(tokens, darkTokens);

  // layout.tsx
  files["src/app/layout.tsx"] = generateLayout();

  // shadcn/ui components (only those actually used)
  const uiImports = new Set<string>();
  // Pre-scan all screens to find which UI components are needed
  for (const screen of project.screens) {
    const screenImports = new Set<string>();
    nodeToJSX(screen.root, 0, screenImports);
    for (const imp of screenImports) uiImports.add(imp);
  }

  if (uiImports.has("Button")) files["src/components/ui/button.tsx"] = buttonComponent();
  if (uiImports.has("Input")) files["src/components/ui/input.tsx"] = inputComponent();
  if (uiImports.has("Badge")) files["src/components/ui/badge.tsx"] = badgeComponent();
  if (uiImports.has("Card")) files["src/components/ui/card.tsx"] = cardComponent();

  // Pages — first screen is the index, rest get their own routes
  for (let i = 0; i < project.screens.length; i++) {
    const screen = project.screens[i];
    const pageImports = new Set<string>();
    const content = generatePage(screen, pageImports);
    const path = i === 0 ? "src/app/page.tsx" : `src/app/${screenSlug(screen.name)}/page.tsx`;
    files[path] = content;
  }

  return { files, dependencies };
}
